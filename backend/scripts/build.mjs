// npm run build  ->  Hostinger-friendly "build": no TypeScript compile (the app runs through tsx).
// It only creates dist/server.js, the entry file Hostinger expects, which migrates the DB and starts src/server.ts.
import fs from 'node:fs';
fs.mkdirSync('dist', { recursive: true });
fs.writeFileSync('dist/server.js', "// generated by scripts/build.mjs\nimport('../scripts/start.mjs').catch((e) => { console.error(e); process.exit(1); });\n");
console.log('Build OK -> dist/server.js');
